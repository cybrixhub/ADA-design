// Single source of truth for the production domain used in metadataBase,
// canonical URLs, Open Graph URLs, the sitemap and robots.txt.
// The NON-WWW domain is the only preferred domain; www is 301-redirected
// to it (see next.config.ts).
export const SITE_HOST = "adadesign.com.au";
export const SITE_URL = `https://${SITE_HOST}`;

export const DEFAULT_TITLE = "ADA Design — Architecture across New South Wales";
export const DEFAULT_DESCRIPTION =
  "Residential, industrial, and medical architecture across NSW. Every project purpose-built for its site.";

/** Absolute URL for a site path, e.g. absoluteUrl("/services") */
export function absoluteUrl(path: string = "/"): string {
  if (path === "/" || path === "") return SITE_URL;
  return `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`;
}

/** Site-wide share image generated by app/opengraph-image.tsx */
export const DEFAULT_OG_IMAGE = {
  url: absoluteUrl("/opengraph-image"),
  width: 1200,
  height: 630,
  type: "image/png",
  alt: DEFAULT_TITLE,
};

/**
 * Open Graph block for a page, so og:url matches the page's canonical URL.
 * A page that defines `openGraph` replaces the layout's block entirely
 * (including the inherited share image), so title, description and image
 * default to the site-wide values here.
 */
export function pageOpenGraph(
  path: string,
  title: string = DEFAULT_TITLE,
  description: string = DEFAULT_DESCRIPTION,
) {
  return {
    title,
    description,
    url: absoluteUrl(path),
    type: "website" as const,
    images: [DEFAULT_OG_IMAGE],
  };
}
